#!/usr/bin/env python3
"""Generate gf256_acch_test.exp — expected values for the bn.gfmul .acch test.

Mirrors BNGFMUL semantics in hw/ip/acc/dv/accsim/sim/insn.py: lanewise
GF(2^8) multiply (poly 0x11b), scalar = byte mod1 of wrs2, XOR-accumulate.
"""
POLY = 0x11B


def gf256_mul(a: int, b: int) -> int:
    a &= 0xFF
    r = 0
    for i in range(8):
        if (b >> i) & 1:
            r ^= a
        a <<= 1
        if a & 0x100:
            a ^= POLY
    return r & 0xFF


def lanes(a256: int, scalar: int) -> int:
    return sum(gf256_mul((a256 >> (8 * i)) & 0xFF, scalar) << (8 * i)
               for i in range(32))


WORDS = [0x12345678, 0x9ABCDEF0] * 4  # val_a, little-endian 32-bit words
A = sum(w << (32 * i) for i, w in enumerate(WORDS))
P2, P3, P7 = lanes(A, 2), lanes(A, 3), lanes(A, 7)

exp = {
    'w0': 0,          # zeroed at test end
    'w10': P2,        # .acc.z   -> ACC  = a*2
    'w11': P3,        # .acch.z  -> ACCH = a*3
    'w12': P3 ^ P7,   # .acch    -> ACCH = a*3 ^ a*7
    'w13': P2 ^ P3,   # .acc     -> ACC  = a*2 ^ a*3 (ACCH ops did not disturb it)
    'w14': P2,        # .acch.z  -> ACCH = a*2 while ACC keeps value
    'w15': P2,        # .acch.inc with mod1=31: b byte31 = 0 -> ACCH unchanged
    'w20': P2,        # bn.wsrr acc  after ACCH-only ops -> independence proof
    'w21': P3 ^ P7,   # bn.wsrr acch
    'w22': P2 ^ P3,   # bn.wsrr acc  after .acch.z -> ACC survives ACCH zeroing
    'w23': P3 ^ P7,   # bn.wsrr acch after .acc -> .acc must not write ACCH
}
print('# gf256_acch_test.exp — AUTO-GENERATED by test_scripts/gf256_acch_expectgen.py')
for k, v in exp.items():
    print(f'{k} = {v:#066x}' if k.startswith('w') else f'{k} = {v}')
print('x8 = 31')   # mod1 readback before .inc
print('x9 = 0')    # mod1 wrapped 31 -> 0 by .acch.inc
