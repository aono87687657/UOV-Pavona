#!/usr/bin/env python3
# Sign-only testvector .s: strips cpk and expect_acc from the shared pkc-skc
# vectors. Sign reads msg_len/msg/sk_seed/sig only; cpk (Ip 43,576 B /
# Is 66,576 B) and expect_acc are dead weight that keeps the RTL harness ELF
# from fitting the 31,744 B bus-visible DMEM window.
#   gen_sign_testvec.py                                    all 25 vector files of ov-<P>-skc/testvectors/, in place
#   gen_sign_testvec.py --param Ip --msglen 0 --out F.s    one file
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[7]
TEST_DATA = REPO / "sw/acc/crypto/handwritten/test_data"
HERE = Path(__file__).resolve().parent
MSGLENS = (0, 1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024)
# the vectors the RTL sign ELFs link: Ip and Is at every message length, Ip3 at 0
ALL = [(p, n) for p in ("Ip", "Is") for n in MSGLENS] + [("Ip3", 0)]

def vectors_dir(param: str) -> Path:
    """Where a parameter set's RTL sign vectors live."""
    return HERE / f"ov-{param}-skc" / "testvectors"


# symbol -> the comment line that opens its block (emission order in the source)
DROP = ("cpk", "expect_acc")


def strip_symbol(text: str, sym: str) -> str:
    """Drop `.balign/.global sym/sym:/…` up to the next .balign that starts
    another block. Keeps the trailing .balign so the next symbol stays aligned."""
    pat = re.compile(
        r"/\*[^*]*\*/\n(?:/\*[^*]*\*/\n)*"      # leading comment block(s)
        r"\.balign 32\n"
        r"\.global " + re.escape(sym) + r"\n"
        r"" + re.escape(sym) + r":\n"
        r"(?:\s*\.word [^\n]*\n|\s*\.zero [^\n]*\n)+"
        r"(?:/\*[^*]*\*/\n)*\n?",
        re.MULTILINE)
    out, n = pat.subn("", text)
    if n != 1:
        sys.exit(f"ERROR: expected exactly 1 block for '{sym}', matched {n}")
    return out


def generate(param: str, msglen: int, out: Path) -> None:
    kat = TEST_DATA / f"testvectors-{param}-pkc-skc"
    # regenerate the full per-msglen .s from the raw KAT, then strip it down
    with tempfile.TemporaryDirectory() as tmp:
        gen_dir = Path(tmp) / f"{param}-pkc-skc"   # -pkc-skc suffix picks the -skc filename prefix
        subprocess.run([sys.executable, str(TEST_DATA / "convert_pkc_to_asm.py"),
                        "--format", param.lower(), str(kat), str(gen_dir)],
                       check=True, capture_output=True, text=True)
        text = (gen_dir / f"testvectors-{param}-pkc-skc_msglen{msglen}.s").read_text()

    for sym in DROP:
        text = strip_symbol(text, sym)

    # fail closed: the four symbols sign needs must survive, the dropped ones must not
    for need in ("msg_len", "msg", "sk_seed", "sig"):
        if f".global {need}\n" not in text:
            sys.exit(f"ERROR: required symbol '{need}' lost")
    for gone in DROP:
        if f".global {gone}\n" in text:
            sys.exit(f"ERROR: '{gone}' survived the strip")

    # Ip3's 135-B signature puts the salt at byte 119, which no word copy can
    # stage; emit it pre-staged where -DUSE_TESTVEC_SALT reads it, so the harness
    # needs no copy and the ELF runs standalone as well as host-fed.
    if param == "Ip3":
        words = [int(w, 16) for w in re.findall(r"0x[0-9a-fA-F]{8}", text.split("\nsig:\n", 1)[1])]
        sig = b"".join(w.to_bytes(4, "little") for w in words)[:135]
        salt = sig[-16:]
        text += ("\n/* Salt = sig[119..134], pre-staged for -DUSE_TESTVEC_SALT (not word aligned in sig) */\n"
                 ".balign 32\n.global salt_input\nsalt_input:\n    .word "
                 + ", ".join(f"0x{int.from_bytes(salt[i:i + 4], 'little'):08x}" for i in range(0, 16, 4))
                 + "\n    .zero 16\n")

    hdr = (f"/* Sign-only test data - {param} msglen {msglen}. Generated by "
           f"gen_sign_testvec.py from\n * {kat.relative_to(REPO)} with cpk and "
           f"expect_acc removed (sign never reads them). */\n")
    out.write_text(hdr + text)
    print(f"{out.name}: {len(text)} B source, kept msg_len/msg/sk_seed/sig")


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Sign-only test vectors for the RTL sign ELFs: the shared pkc-skc vectors without cpk and "
                    "expect_acc. With no option, all 25 vector files of ov-<P>-skc/testvectors/ are written in place.")
    ap.add_argument("--param", choices=("Ip", "Is", "Ip3"), help="parameter set")
    ap.add_argument("--msglen", type=int, choices=MSGLENS, help="message length of the KAT case")
    ap.add_argument("--out", type=Path, help="the .s file to write")
    a = ap.parse_args()
    one = (a.param, a.msglen, a.out)
    if one == (None, None, None):
        todo = [(p, n, vectors_dir(p) / f"testvectors-{p}-sign_msglen{n}.s") for p, n in ALL]
    elif None in one:
        ap.error("--param, --msglen and --out go together")
    else:
        todo = [one]
    for param, msglen, out in todo:
        generate(param, msglen, out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
