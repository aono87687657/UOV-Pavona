#!/usr/bin/env python3
"""Emit the host-side fixtures for the chip-level one-shot keygen test.

Two kinds of header, both derived, never hand-copied:
  --vectors : keygen_oneshot_<param>_testvec.h - seed A (KAT case 0) and its cpk,
              seed B (a different keypair: case 1, or the .nistkat key 0 for Ip3)
              and its cpk. Shared by every kernel of the parameter set.
  --geom    : keygen_oneshot_geom_<app>.h - the DMEM addresses of sk_seed/csk and
              cpk, the cpk and guard lengths, and the poison intervals of THIS
              ELF's layout: `_min` poisons the packed payload only (its guard is
              reserved zero and never rewritten), `_sp` poisons the payload, the
              triangle accumulator (with the guard the kernel clears), the P1
              buffer, the T rows, the frame and the P2 buffer - never the AES
              constants. Intervals are byte-granular; the driver preserves the
              other bytes of a partial word.

Usage (from the repo root):
  gen_keygen_oneshot_testvec.py --vectors --param Ip > sw/device/tests/acc_uov/keygen_oneshot_ip_testvec.h
  gen_keygen_oneshot_testvec.py --geom --param Ip --app ov_Ip_keygen_sp_bngfaes \\
      --elf bazel-bin/.../ov_Ip_keygen_sp_bngfaes.elf > sw/device/tests/acc_uov/keygen_oneshot_geom_ov_Ip_keygen_sp_bngfaes.h
"""
import argparse
import contextlib
import hashlib
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(_HERE, '..', '..', '..', '..'))
sys.path.insert(0, REPO)
sys.path.insert(0, os.path.join(REPO, 'sw/acc/crypto/handwritten/own_utils'))
from ov_keygen_test_utils import _kg_objdump_syms, _kg_parse_pkc_skc

PARAMS = {  # cpk bytes, guard bytes after cpk (Ip, Ip3: reserved zero), second-key source
    'Ip': (16 + 990 * 44, 8, None),
    'Ip3': (16 + 1035 * 45, 8, '.nistkat'),
    'Is': (16 + 2080 * 32, 0, None),
}




def load_hash(elf):
    """sha256 over every PT_LOAD segment (address, sizes, bytes): what the chip loads.
    The whole file also embeds build paths, which differ between output bases."""
    from elftools.elf.elffile import ELFFile
    h = hashlib.sha256()
    for s in ELFFile(open(elf, 'rb')).iter_segments():
        if s['p_type'] == 'PT_LOAD':
            h.update(b'%x %x %x ' % (s['p_paddr'], s['p_filesz'], s['p_memsz']) + s.data())
    return h.hexdigest()[:16]


def carr(name, data, per_line=12):
    out = [f'static const uint8_t {name}[{len(data)}] = {{']
    for i in range(0, len(data), per_line):
        out.append('    ' + ' '.join(f'0x{b:02x},' for b in data[i:i + per_line]))
    out.append('};')
    return '\n'.join(out)


def vectors(a):
    cpk_len, guard, second = PARAMS[a.param]
    src = os.path.join(REPO, 'sw/acc/crypto/handwritten/test_data', f'testvectors-{a.param}-pkc-skc')
    with contextlib.redirect_stdout(sys.stderr):
        cases = _kg_parse_pkc_skc(src)
        cpk_a, seed_a = cases[a.case]
        if second:
            cpk_b, seed_b = _kg_parse_pkc_skc(src + second)[0]
            b_desc, b_file = f'{os.path.basename(src)}{second} key 0', src + second
        else:
            cpk_b, seed_b = cases[(a.case + 1) % len(cases)]
            b_desc, b_file = f'{os.path.basename(src)} case {(a.case + 1) % len(cases)}', src
    cpk_a, cpk_b, seed_a, seed_b = bytes(cpk_a), bytes(cpk_b), bytes(seed_a), bytes(seed_b)
    if len(cpk_a) != cpk_len or len(cpk_b) != cpk_len:
        raise SystemExit(f'cpk is {len(cpk_a)} / {len(cpk_b)} B, expected {cpk_len}')
    if seed_a == seed_b:
        raise SystemExit('seeds A and B must differ')
    h = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()[:16]
    print('// Generated by gen_keygen_oneshot_testvec.py --vectors; do not edit.')
    print(f'// {a.param}: seed A = {os.path.basename(src)} case {a.case} (file sha256 {h(src)}..), seed B = {b_desc} (file sha256 {h(b_file)}..).')
    print('#include <stdint.h>')
    print(f'#define KEYGEN_ONESHOT_CPK_LEN {cpk_len}u')
    print(f'#define KEYGEN_ONESHOT_GUARD_LEN {guard}u')
    print(carr('kSkSeedA', seed_a))
    print(carr('kSkSeedB', seed_b))
    print(carr('kCpkA', cpk_a))
    print(carr('kCpkB', cpk_b))


def geom(a):
    cpk_len, guard, _ = PARAMS[a.param]
    sym = _kg_objdump_syms(a.elf)
    for s in ('sk_seed', 'csk', 'cpk', 'cpk_payload', '_dmem_data_end'):
        if s not in sym:
            raise SystemExit(f'{a.elf}: no symbol {s}')
    if sym['csk'] != sym['sk_seed']:
        raise SystemExit('csk must alias sk_seed (one-shot contract)')
    if sym['cpk_payload'] != sym['cpk'] + 16:
        raise SystemExit('cpk_payload must follow the 16-B prefix')
    if sym['cpk'] + cpk_len + guard > sym['_dmem_data_end']:
        raise SystemExit('cpk + guard must lie inside the linked image')
    payload = sym['cpk_payload']
    payload_len = cpk_len - 16
    if a.app.endswith('_min') or '_min_' in a.app:
        family = 'min'
        ivals = [(payload, payload_len)]                       # the guard stays reserved zero
    else:
        family = 'sp'
        if 'tri_end' in sym:                                   # Ip / Ip3: payload + tri (guard inside tri)
            ivals = [(payload, sym['tri_end'] - payload)]
        else:                                                  # Is: the payload is the accumulator
            ivals = [(payload, payload_len)]
        ivals.append((sym['p1buf'], sym['frame'] + 64 - sym['p1buf']))   # p1buf, T rows, (Is: o_ctx before p1buf handled below), frame
        if 'o_ctx' in sym and 'cpk_payload_end' in sym:
            ivals = [(payload, sym['frame'] + 64 - payload)]   # Is `_sp`: payload..frame contiguous (o_ctx, p1buf, T rows, rkbuf, ivb, frame)
        if 'p2buf' in sym:
            ivals.append((sym['p2buf'], 3584))
    ivals.sort()
    for (x0, n0), (x1, n1) in zip(ivals, ivals[1:]):
        if x0 + n0 > x1:
            raise SystemExit(f'overlapping poison intervals {ivals}')
    if ivals[-1][0] + ivals[-1][1] > sym['_dmem_data_end']:
        raise SystemExit('poison interval past the linked image')
    print(f'// Generated by gen_keygen_oneshot_testvec.py --geom for {a.app}; do not edit.')
    print(f'// ELF {os.path.basename(a.elf)} loadable image sha256 {load_hash(a.elf)}..; linked end {sym["_dmem_data_end"]:#x}.')
    print('#include <stdint.h>')
    print(f'#define KEYGEN_ONESHOT_FAMILY "{family}"')
    print(f'#define KEYGEN_ONESHOT_SEED_ADDR {sym["sk_seed"]:#x}u')
    print(f'#define KEYGEN_ONESHOT_CPK_ADDR {sym["cpk"]:#x}u')
    print(f'#define KEYGEN_ONESHOT_DATA_END {sym["_dmem_data_end"]:#x}u')
    print(f'#define KEYGEN_ONESHOT_POISON_COUNT {len(ivals)}u')
    print('static const struct { uint32_t addr; uint32_t len; } kPoison[] = {')
    for x, n in ivals:
        print(f'    {{{x:#x}u, {n}u}},')
    print('};')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--vectors', action='store_true')
    ap.add_argument('--geom', action='store_true')
    ap.add_argument('--param', choices=sorted(PARAMS), required=True)
    ap.add_argument('--case', type=int, default=0)
    ap.add_argument('--app', default='', help='acc_binary name (geom)')
    ap.add_argument('--elf', default='', help='that app\'s ELF (geom)')
    a = ap.parse_args()
    if a.vectors == a.geom:
        raise SystemExit('pick --vectors or --geom')
    if a.vectors:
        vectors(a)
    else:
        if not (a.app and a.elf):
            raise SystemExit('--geom needs --app and --elf')
        geom(a)


if __name__ == '__main__':
    main()
